def glyph(font, ch):
    rows = font[ch]
    return np.array([[c == "#" for c in r] for r in rows], bool)


def text_mask(text, font=SMALL, spacing=1, space=None):
    """Bitmap of a line of text, one cell per glyph pixel."""
    h = len(next(iter(font.values())))
    cols = []
    for i, ch in enumerate(text):
        if ch == " " and space is not None:
            cols.append(np.zeros((h, space), bool))
        else:
            cols.append(glyph(font, ch if ch in font else ch.upper()))
        if i < len(text) - 1:
            cols.append(np.zeros((h, spacing), bool))
    return np.concatenate(cols, axis=1)


def wordmark_mask():
    """'DEEP FIELD' in the display font: 73x10 cells."""
    return text_mask("DEEP FIELD", DISPLAY, spacing=2, space=3)
