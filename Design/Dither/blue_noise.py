#!/usr/bin/env python3
"""Generates the 64x64 blue-noise threshold tile for the "Blue noise" dither pattern.

Void-and-cluster (Ulichney 1993): each new threshold goes to the emptiest spot of the pattern
so far, measured with a toroidal Gaussian, so the tile has no low-frequency clumps and wraps
without a seam. Writes Sources/DeepField/Rendering/Shaders/ShaderBlueNoise.swift.

    python3 Design/Dither/blue_noise.py
"""
import pathlib

import numpy as np

N = 64
SIGMA = 1.9
OUT = pathlib.Path(__file__).resolve().parents[2] / "Sources/DeepField/Rendering/Shaders/ShaderBlueNoise.swift"


def kernel():
    d = np.minimum(np.arange(N), N - np.arange(N))
    g = np.exp(-(d[:, None] ** 2 + d[None, :] ** 2) / (2 * SIGMA**2))
    return g


def energy_of(pattern, g):
    return np.real(np.fft.ifft2(np.fft.fft2(pattern) * np.fft.fft2(g)))


def tightest(pattern, energy):
    e = np.where(pattern, energy, -np.inf)
    return np.unravel_index(np.argmax(e), e.shape)


def largest_void(pattern, energy):
    e = np.where(pattern, np.inf, energy)
    return np.unravel_index(np.argmin(e), e.shape)


def shifted(g, y, x):
    return np.roll(np.roll(g, y, axis=0), x, axis=1)


def main():
    g = kernel()
    rng = np.random.default_rng(1)
    # Initial binary pattern: 10% random points, relaxed until the tightest cluster and the
    # largest void are the same spot.
    pattern = np.zeros((N, N), bool)
    pattern.flat[rng.choice(N * N, N * N // 10, replace=False)] = True
    energy = energy_of(pattern, g)
    while True:
        cy, cx = tightest(pattern, energy)
        pattern[cy, cx] = False
        energy -= shifted(g, cy, cx)
        vy, vx = largest_void(pattern, energy)
        if (vy, vx) == (cy, cx):
            pattern[cy, cx] = True
            energy += shifted(g, cy, cx)
            break
        pattern[vy, vx] = True
        energy += shifted(g, vy, vx)

    initial = pattern.copy()
    ones = int(initial.sum())
    rank = np.zeros((N, N), int)

    # Phase 1: remove the tightest clusters from the initial pattern, ranking downward.
    p, e = initial.copy(), energy_of(initial, g)
    for r in range(ones - 1, -1, -1):
        y, x = tightest(p, e)
        p[y, x] = False
        e -= shifted(g, y, x)
        rank[y, x] = r

    # Phases 2 and 3: fill the largest voids, ranking upward.
    p, e = initial.copy(), energy_of(initial, g)
    for r in range(ones, N * N):
        y, x = largest_void(p, e)
        p[y, x] = True
        e += shifted(g, y, x)
        rank[y, x] = r

    values = (rank * 256 // (N * N)).astype(int).flatten()
    rows = [", ".join(str(v) for v in values[i : i + 32]) for i in range(0, N * N, 32)]
    body = ",\n".join(rows)
    OUT.write_text(
        "// Generated by Design/Dither/blue_noise.py. Do not edit by hand.\n\n"
        "extension ShaderSource {\n"
        "    /// A 64x64 blue-noise threshold tile (void-and-cluster), ranks scaled to 0..255.\n"
        '    static let blueNoise = """\n'
        "constant uchar blueNoise64[4096] = {\n"
        f"{body}\n"
        "};\n"
        '"""\n'
        "}\n"
    )
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
